"""Generate German names and evolution-family IDs from pinned PokéAPI CSV data."""
import csv
import io
import json
import pathlib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
REVISION = "193d8d4fbb57cf962e3f7c1ce5299a6fe847b3f8"
BASE = f"https://raw.githubusercontent.com/PokeAPI/pokeapi/{REVISION}/data/v2/csv/"


def rows(file):
    with urllib.request.urlopen(BASE + file + ".csv", timeout=30) as response:
        return list(csv.DictReader(io.StringIO(response.read().decode("utf-8"))))


def names(file, key, limit):
    return {int(row[key]): row["name"] for row in rows(file)
            if row["local_language_id"] == "6" and int(row[key]) <= limit}


def quote(value):
    return json.dumps(value, ensure_ascii=False)


german = names("pokemon_species_names", "pokemon_species_id", 386)
moves = names("move_names", "move_id", 354)
species = [row for row in rows("pokemon_species") if 1 <= int(row["id"]) <= 386]
assert len(german) == len(species) == 386 and len(moves) == 354
lines = ["namespace SoulLink;", "", "// Generated by scripts/update-ruby-names.py.", "public static partial class RubyNames", "{",
         "    private static readonly SpeciesName[] SpeciesByDex =", "    [", "        new(0, \"\", \"\"),"]
for row in sorted(species, key=lambda row: int(row["id"])):
    lines.append(f'        new({row["evolution_chain_id"]}, {quote(german[int(row["id"])])}, {quote(row["identifier"])}),')
lines += ["    ];", "", "    private static readonly string[] MoveById =", "    [", '        "",']
lines += ["        " + quote(moves[index]) + "," for index in range(1, 355)]
lines += ["    ];", "}", ""]
(ROOT / "SoulLink/RubyNames.Data.cs").write_bytes("\r\n".join(lines).encode("utf-8"))
