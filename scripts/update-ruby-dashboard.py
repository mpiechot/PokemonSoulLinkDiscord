"""Generate factual dashboard metadata without bundling game artwork."""
import concurrent.futures
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOCK = json.loads((ROOT / "integration/mgba/sources.json").read_text(encoding="utf-8"))
BASE = "https://raw.githubusercontent.com/pret/pokeruby/" + LOCK["pokeruby"] + "/"


def fetch(path):
    with urllib.request.urlopen(BASE + path, timeout=30) as response:
        return response.read().decode("utf-8", errors="replace")


paths = ("include/constants/species.h", "src/data/pokemon/base_stats.h",
         "src/data/region_map/region_map_sections.json", "src/data/trainer_parties.h")
with concurrent.futures.ThreadPoolExecutor(max_workers=len(paths)) as pool:
    definitions, stats, sections_json, parties = pool.map(fetch, paths)
internal = dict(re.findall(r"^#define SPECIES_(\w+) (\d+)$", definitions, re.M))
national = dict(re.findall(r"^#define NATIONAL_DEX_(\w+) (\d+)$", definitions, re.M))
forms = []
for species, dex in national.items():
    if not 1 <= int(dex) <= 386:
        continue
    match = re.search(rf"\[SPECIES_{species}\]\s*=\s*\{{([^}}]+)\}}", stats)
    types = re.findall(r"\.type[12]\s*=\s*TYPE_(\w+)", match.group(1))
    assert len(types) == 2, species
    forms.append((int(internal[species]), int(dex), *(kind.lower() for kind in types)))
forms.sort()
assert len(forms) == 386 and len({form[1] for form in forms}) == 386
sections = json.loads(sections_json)["map_sections"]
leaders = zip(
    ("Roxanne", "Brawly", "Wattson", "Flannery", "Norman", "Winona", "TateAndLiza", "Wallace"),
    ("Felizia", "Kamillo", "Walter", "Flavia", "Norman", "Wibke", "Ben & Svenja", "Wassili"),
    (10, 2, 9, 3, 7, 11, 13, 14),
)
gym_rows = []
for number, (symbol, name, area) in enumerate(leaders, 1):
    block = re.search(rf"gTrainerParty_{symbol}\[\] = \{{(.*?)\n\}};", parties, re.S).group(1)
    levels = re.findall(r"\.level = (\d+)", block)
    assert levels
    gym_rows.append(f'        new({number}, "{name}", {area}, [{", ".join(levels)}]),')
form_rows = [f'        [{species}] = new({dex}, "{one}", "{two}"),' for species, dex, one, two in forms]
map_rows = [f'        new({i}, {s["x"]}, {s["y"]}, {s["width"]}, {s["height"]}),'
            for i, s in enumerate(sections) if s["id"] not in
            {"MAPSEC_INSIDE_OF_TRUCK", "MAPSEC_SECRET_BASE", "MAPSEC_DYNAMIC"}]

content = """namespace SoulLink;

// Generated by scripts/update-ruby-dashboard.py from the pinned Ruby source.
public sealed record RubySpeciesAppearance(int NationalDex, string Type1, string Type2);
public sealed record RubyMapArea(int Area, int X, int Y, int Width, int Height);
public sealed record RubyGym(int Number, string Name, int Area, int[] Levels);

public static class RubyDashboardCatalog
{
    private static readonly Dictionary<int, RubySpeciesAppearance> Forms = new()
    {
""" + "\n".join(form_rows) + """
    };

    public static IReadOnlyList<RubyMapArea> Areas { get; } =
    [
""" + "\n".join(map_rows) + """
    ];

    public static IReadOnlyList<RubyGym> Gyms { get; } =
    [
""" + "\n".join(gym_rows) + """
    ];

    public static RubySpeciesAppearance? Appearance(int species) => Forms.GetValueOrDefault(species);

    public static RubyGym? NextGym(byte badges) => Gyms.FirstOrDefault(gym => (badges & (1 << (gym.Number - 1))) == 0);
}
"""
(ROOT / "SoulLink/RubyDashboardCatalog.cs").write_bytes(content.replace("\n", "\r\n").encode("utf-8"))
print(f"Generated {len(forms)} species, {len(map_rows)} schematic map areas and {len(gym_rows)} gyms.")
